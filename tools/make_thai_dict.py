#!/usr/bin/env python3
"""Pack ICU's Thai word list into src/thai_dict.inc for the reader's line breaking.

Thai writes no spaces between words, so a line may only break where the reader
knows a word ends. The list is ICU's thaidict.txt (Unicode licence, see
THIRD-PARTY.md):

  curl -sSfLO https://raw.githubusercontent.com/unicode-org/icu/main/icu4c/source/data/brkitr/dictionaries/thaidict.txt
  python3 tools/make_thai_dict.py thaidict.txt > toybox-core/src/tools/thai_dict.inc

Format (toybox-core/src/tools/thai_words.h reads it): every Thai letter is one
byte, its codepoint minus U+0E00. Words are sorted bytewise and front-coded in
blocks of BLOCK: a block's first word is <len><bytes>, each next word is
<shared prefix len><suffix len><suffix bytes>. THAI_DICT_INDEX holds each
block's byte offset, so a lookup is a binary search on the blocks' first words
and a short walk inside one block.
"""
import sys

BLOCK = 16


def main():
    words = set()
    with open(sys.argv[1], encoding='utf-8-sig') as f:
        for line in f:
            w = line.strip()
            if not w or w.startswith('#'):
                continue
            if all(0x0E01 <= ord(c) <= 0x0E5B for c in w):
                words.add(bytes(ord(c) - 0x0E00 for c in w))
    words = sorted(words)
    data, index = bytearray(), []
    longest = 0
    for i, w in enumerate(words):
        longest = max(longest, len(w))
        assert len(w) < 256
        if i % BLOCK == 0:
            index.append(len(data))
            data += bytes([len(w)]) + w
        else:
            prev = words[i - 1]
            k = 0
            while k < min(len(prev), len(w)) and prev[k] == w[k]:
                k += 1
            data += bytes([k, len(w) - k]) + w[k:]
    out = sys.stdout
    out.write('// Generated by tools/make_thai_dict.py from ICU thaidict.txt -- do not edit.\n')
    out.write('// Copyright (C) 2016 and later: Unicode, Inc. and others.\n')
    out.write('// Copyright (c) 2006-2015 International Business Machines Corporation,\n')
    out.write('// Apple Inc., and others. Unicode licence: see THIRD-PARTY.md.\n')
    out.write(f'inline constexpr int THAI_DICT_WORDS = {len(words)};\n')
    out.write(f'inline constexpr int THAI_DICT_BLOCK = {BLOCK};\n')
    out.write(f'inline constexpr int THAI_DICT_BLOCKS = {len(index)};\n')
    out.write(f'inline constexpr int THAI_DICT_LONGEST = {longest};\n')
    out.write('inline const uint32_t THAI_DICT_INDEX[] = {\n')
    for i in range(0, len(index), 12):
        out.write('  ' + ', '.join(str(x) for x in index[i:i + 12]) + ',\n')
    out.write('};\n')
    out.write(f'inline const uint8_t THAI_DICT_DATA[{len(data)}] = {{\n')
    for i in range(0, len(data), 24):
        out.write('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',\n')
    out.write('};\n')
    print(f'{len(words)} words, longest {longest} letters, {len(data)} + {4 * len(index)} bytes',
          file=sys.stderr)


if __name__ == '__main__':
    main()
