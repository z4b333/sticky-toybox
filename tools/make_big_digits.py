#!/usr/bin/env python3
"""Big bold digits for numbers past the UI fonts' 44 px (Random's result).

Noto Sans SemiBold, thickened by a stroke, rasterised 1 bit at one size.
Writes toybox-core/src/tools/big_digits.h. Run: python3 tools/make_big_digits.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'toybox-core', 'src', 'tools', 'big_digits.h')
SIZE, STROKE = 168, 2
font = ImageFont.truetype(os.path.join(HERE, 'fonts', 'NotoSans-SemiBold.ttf'), SIZE)
tops, bots = [], []
for ch in '0123456789':
    l, t, r, b = font.getbbox(ch, stroke_width=STROKE)
    tops.append(t); bots.append(b)
top, bot = min(tops), max(bots)
H = bot - top
lines = ['// GENERATED by tools/make_big_digits.py -- do not edit by hand.',
         '// Noto Sans SemiBold (SIL OFL 1.1), thickened, 1 bit, MSB first, 1 = ink.',
         '#pragma once', '#include <stdint.h>', '#include <pgmspace.h>', '',
         'namespace bigdigits {', f'inline constexpr int H = {H};']
widths, offs, data = [], [], []
for ch in '0123456789':
    adv = int(round(font.getlength(ch))) + STROKE * 2
    im = Image.new('1', (adv, H), 0)
    ImageDraw.Draw(im).text((STROKE, -top), ch, font=font, fill=1, stroke_width=STROKE, stroke_fill=1)
    stride = (adv + 7) // 8
    offs.append(len(data)); widths.append(adv)
    px = im.load()
    for y in range(H):
        for xb in range(stride):
            v = 0
            for k in range(8):
                x = xb * 8 + k
                if x < adv and px[x, y]: v |= 0x80 >> k
            data.append(v)
lines.append('inline constexpr uint8_t W[10] = {' + ','.join(map(str, widths)) + '};')
lines.append('inline constexpr uint32_t OFF[10] = {' + ','.join(map(str, offs)) + '};')
lines.append('const uint8_t BITS[] PROGMEM = {')
for i in range(0, len(data), 24):
    lines.append('  ' + ','.join(f'0x{v:02X}' for v in data[i:i + 24]) + ',')
lines.append('};')
lines += ['', '// Width of a run of digits (other characters are skipped).',
'inline int width(const char* s) {', '  int w = 0;', "  for (; *s; ++s) if (*s >= '0' && *s <= '9') w += W[*s - '0'];", '  return w;', '}',
'// Draws digits with their top at y, centred on cx, as row runs.',
'template <class Canvas>', 'inline void drawCentered(Canvas& c, int cx, int y, const char* s, bool black = true) {',
'  int x = cx - width(s) / 2;', '  for (; *s; ++s) {', "    if (*s < '0' || *s > '9') continue;",
"    const int d = *s - '0', dw = W[d], stride = (dw + 7) / 8;", '    const uint8_t* bits = BITS + OFF[d];',
'    for (int row = 0; row < H; row++) {', '      int run = -1;', '      for (int col = 0; col <= dw; col++) {',
'        const bool ink = col < dw && (pgm_read_byte(bits + row * stride + col / 8) & (0x80 >> (col & 7)));',
'        if (ink && run < 0) run = col;', '        if (!ink && run >= 0) {', '          c.fillRect(x + run, y + row, col - run, 1, black);',
'          run = -1;', '        }', '      }', '    }', '    x += dw;', '  }', '}', '}  // namespace bigdigits']
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', OUT, 'H', H, 'bytes', len(data))
